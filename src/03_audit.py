"""Hands-on audit of CUAD: alignment, duplicates, overlap between contracts, label sparsity, span geometry."""
import pathlib, duckdb, pandas as pd, numpy as np
ROOT = pathlib.Path(__file__).resolve().parents[1]
con = duckdb.connect(str(ROOT / "data/cuad.duckdb"), read_only=True)
seg = pd.read_parquet(ROOT / "data/segments.parquet", columns=["contract_id", "start", "end", "text"])
lines = ["# Data audit (generated by src/03_audit.py)\n"]
c = con.execute("select * from contracts").df()
lines.append(f"- {len(c)} contracts, {c.company.nunique()} distinct companies, {c.agreement_type.nunique()} distinct normalized agreement types.")
top = c.agreement_type.value_counts()
lines.append(f"- {int((top>1).sum())} agreement types appear more than once; the 10 largest cover {top.head(10).sum()} contracts ({top.head(10).sum()/len(c):.0%}).")
multi = c.company.value_counts(); lines.append(f"- {int((multi>1).sum())} companies contribute 2+ contracts ({int(multi[multi>1].sum())} contracts).")
s = con.execute("select * from spans").df()
lines.append(f"- {len(s)} labelled spans; median length {int((s.end-s.start).median())} characters, 90th percentile {int((s.end-s.start).quantile(.9))}, longest {int((s.end-s.start).max())}.")
dup = s.duplicated(["contract_id", "category", "start", "end"]).sum()
lines.append(f"- duplicate (contract, category, start, end) spans: {dup}.")
ov = s.sort_values(["contract_id", "category", "start"])
ov["prev_end"] = ov.groupby(["contract_id", "category"]).end.shift()
lines.append(f"- spans overlapping another span of the same category in the same contract: {int((ov.start < ov.prev_end).sum())}.")
n_cat = s.groupby("contract_id").category.nunique()
lines.append(f"- categories with at least one span per contract: median {int(n_cat.median())} of 41 (min {int(n_cat.min())}, max {int(n_cat.max())}).")
# co-occurrence of the same text under different categories
dd = s.groupby(["contract_id", "start", "end"]).category.nunique()
lines.append(f"- {int((dd>1).sum())} identical spans carry 2+ categories (one clause, several labels).")
# length vs clause presence
cl = c.n_chars
lines.append(f"- contract length: median {int(cl.median()):,} characters, 5th pct {int(cl.quantile(.05)):,}, 95th pct {int(cl.quantile(.95)):,}, max {int(cl.max()):,}.")
lines.append(f"- total segments {len(seg):,}; median {int(seg.text.str.len().median())} characters.")
# duplicated segment text across contracts = boilerplate
vc = seg.text.value_counts()
rep = vc[vc > 1]
lines.append(f"- {len(rep):,} distinct segment texts occur in 2+ contracts, covering {int(rep.sum()):,} segments ({rep.sum()/len(seg):.1%}). This is boilerplate shared across contracts and a leakage route for random splits.")
open(ROOT / "outputs/audit.md", "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("\n".join(lines))
