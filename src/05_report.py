"""Summaries and charts from outputs/results_by_category.csv."""
import pathlib, numpy as np, pandas as pd, matplotlib
matplotlib.use("Agg"); import matplotlib.pyplot as plt
ROOT = pathlib.Path(__file__).resolve().parents[1]
r = pd.read_csv(ROOT / "outputs/results_by_category.csv")
names = {"random_segments": "Random segments", "random_contracts": "Random contracts",
         "company_held_out": "Company held out", "type_held_out": "Agreement type held out"}
order = list(names)
m = r.groupby(["scheme", "model"])[["seg_aupr", "contract_aupr", "hit_at_3"]].mean().round(3)
m.to_csv(ROOT / "outputs/summary_macro.csv")
rules_cats = r[r.model == "rules"].category.unique()
mr = r[r.category.isin(rules_cats)].groupby(["scheme", "model"])[["seg_aupr", "hit_at_3"]].mean().round(3)
mr.to_csv(ROOT / "outputs/summary_rules_categories.csv")
# paired comparison per category
w = r[r.model == "tfidf"].pivot(index="category", columns="scheme", values="seg_aupr")
d = w["random_segments"] - w["random_contracts"]
lines = ["# Summary (generated by src/05_report.py)\n",
         f"Macro-average over {r.category.nunique()} clause categories.\n", m.to_markdown(), "",
         f"On the {len(rules_cats)} categories that have a keyword rule:\n", mr.to_markdown(), "",
         f"TF-IDF segment AUPR: random segments minus random contracts = {d.mean():+.3f} on average; "
         f"higher in {int((d>0).sum())} of {len(d)} categories.",
         f"TF-IDF segment AUPR: random contracts minus company held out = {(w['random_contracts']-w['company_held_out']).mean():+.3f}; "
         f"minus agreement type held out = {(w['random_contracts']-w['type_held_out']).mean():+.3f}."]
(ROOT / "outputs/summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("\n".join(lines))
C = {"tfidf": "#1b6ca8", "minilm": "#c97b1a", "rules": "#7a7a7a"}
# chart 1: macro AUPR by split and model
fig, ax = plt.subplots(figsize=(7.5, 4))
x = np.arange(len(order)); wd = 0.26
for i, mod in enumerate(["tfidf", "minilm"]):
    v = [m.loc[(s, mod), "seg_aupr"] for s in order]
    ax.bar(x + (i - .5) * wd, v, wd, label={"tfidf": "TF-IDF + logistic regression", "minilm": "MiniLM embeddings + logistic regression"}[mod], color=C[mod])
    for xi, vi in zip(x + (i - .5) * wd, v): ax.text(xi, vi + .006, f"{vi:.2f}", ha="center", fontsize=8)
ax.set_xticks(x); ax.set_xticklabels([names[s] for s in order], fontsize=9)
ax.set_ylabel("Segment AUPR (macro, 39 clause types)"); ax.legend(frameon=False, fontsize=8, loc="upper right")
ax.set_title("Clause finding under four ways of splitting the data", fontsize=10, loc="left")
for s in ("top", "right"): ax.spines[s].set_visible(False)
fig.tight_layout(); fig.savefig(ROOT / "docs/img/splits.png", dpi=160); plt.close(fig)
# chart 2: per category, tfidf, contract-level split
t = r[(r.model == "tfidf") & (r.scheme == "random_contracts")].sort_values("seg_aupr")
fig, ax = plt.subplots(figsize=(7.5, 8))
ax.barh(t.category, t.seg_aupr, color=C["tfidf"]); ax.set_xlabel("Segment AUPR (contracts held out)")
ax.set_title("Which clauses are easy to find", fontsize=10, loc="left")
for s in ("top", "right"): ax.spines[s].set_visible(False)
ax.tick_params(axis="y", labelsize=7); fig.tight_layout(); fig.savefig(ROOT / "docs/img/by_category.png", dpi=160); plt.close(fig)
# chart 3: rules vs tfidf, same categories
rr = r[(r.scheme == "random_contracts") & r.category.isin(rules_cats) & r.model.isin(["rules", "tfidf"])].pivot(index="category", columns="model", values="hit_at_3").sort_values("tfidf")
fig, ax = plt.subplots(figsize=(7.5, 5)); y = np.arange(len(rr))
ax.barh(y + .2, rr.tfidf, .4, color=C["tfidf"], label="TF-IDF + logistic regression"); ax.barh(y - .2, rr.rules, .4, color=C["rules"], label="Keyword rules")
ax.set_yticks(y); ax.set_yticklabels(rr.index, fontsize=7); ax.set_xlabel("Share of contracts where a top-3 segment is a labelled clause")
ax.legend(frameon=False, fontsize=8, loc="lower right"); ax.set_title("Hand-written keyword rules against a trained scorer", fontsize=10, loc="left")
for s in ("top", "right"): ax.spines[s].set_visible(False)
fig.tight_layout(); fig.savefig(ROOT / "docs/img/rules_vs_model.png", dpi=160); plt.close(fig)
